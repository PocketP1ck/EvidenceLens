import fs from "node:fs/promises";
import { INVESTIGATIONS_DIR } from "@/lib/config";
import { resolveRunFile } from "@/lib/harness/store";

export const dynamic = "force-dynamic";

const TYPES: Record<string, string> = {
  svg: "image/svg+xml",
  png: "image/png",
  cif: "chemical/x-cif",
  pdb: "chemical/x-pdb",
  md: "text/markdown; charset=utf-8",
};

export async function GET(_req: Request, { params }: { params: Promise<{ id: string; sub: string; name: string }> }) {
  const { id, sub, name } = await params;
  const file = resolveRunFile(INVESTIGATIONS_DIR, id, sub, name);
  if (!file) return new Response("Not found", { status: 404 });
  try {
    const body = await fs.readFile(file);
    const ext = name.split(".").pop()?.toLowerCase() ?? "";
    return new Response(body, {
      headers: {
        "content-type": TYPES[ext] ?? "application/octet-stream",
        "cache-control": "no-cache",
        // SVGs are generated by us, but serve them inertly anyway.
        "content-security-policy": "default-src 'none'; style-src 'unsafe-inline'",
        "x-content-type-options": "nosniff",
      },
    });
  } catch {
    return new Response("Not found", { status: 404 });
  }
}
